// Regenerates every rendering of the Hatch mark from its one source,
// packages/ui/src/brand/hatchMark.ts:
//
//   hatch-logo.svg                           the repository root's logo
//   packages/ui/src/assets/hatch-logo.svg    the copy the site's bundler reaches
//   apps/hatch/public/favicon.svg            the board's tab icon
//   apps/auth/public/favicon.svg             the sign-in page's tab icon and mark
//   apps/hatch/public/icons/*.png            the PWA icons and the Apple touch icon
//
// Run with `npm run icons` (apps/hatch). Never invoked by a build - only a
// person changing the mark runs this, so the build needs no image tooling.
// Node strips the types out of the .ts import itself; the flag in
// package.json's script asks for that on a Node older than 22.18, where it
// is not yet the default. brandAssets.test.ts refuses an SVG that drifts from
// the source; the PNGs are not compared, since a raster differs by sharp
// version, so look at them after regenerating.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { hatchIconSvg, hatchMarkSvg } from '../../../packages/ui/src/brand/hatchMark.ts';

const __dirname = dirname(fileURLToPath(import.meta.url));
const web = resolve(__dirname, '../../..');
const root = resolve(web, '../..');
const iconsDir = resolve(__dirname, '../public/icons');

const logo = hatchMarkSvg({
  fill: 'gradient',
  comment: 'Generated by `npm run icons` in apps/hatch from packages/ui/src/brand/hatchMark.ts. Edit that file, not this one.',
});

const svgs = [
  resolve(root, 'hatch-logo.svg'),
  resolve(web, 'packages/ui/src/assets/hatch-logo.svg'),
  resolve(web, 'apps/hatch/public/favicon.svg'),
  resolve(web, 'apps/auth/public/favicon.svg'),
];

/** Rasterised at exactly `size`, rather than drawn once and resized: a
    rasterised SVG is sharp at the size it was drawn for. */
async function png(shape, size, file) {
  await sharp(Buffer.from(hatchIconSvg({ size, shape })))
    .png()
    .toFile(resolve(iconsDir, file));
}

async function main() {
  await mkdir(iconsDir, { recursive: true });
  for (const file of svgs) await writeFile(file, logo);

  // Shown as they are, so the squircle carries its own transparent corners.
  await png('squircle', 192, 'icon-192.png');
  await png('squircle', 512, 'icon-512.png');

  // Masked by the platform to whatever shape it likes, so the gradient runs to
  // every edge and the egg keeps inside the maskable spec's centre-80% safe
  // zone. iOS cuts the touch icon the same way.
  await png('square', 512, 'icon-512-maskable.png');
  await png('square', 180, 'apple-touch-icon.png');
}

main();
