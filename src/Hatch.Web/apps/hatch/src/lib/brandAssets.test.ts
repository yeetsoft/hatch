/* The mark has one source, packages/ui/src/brand/hatchMark.ts, and four SVG
   files generated from it by `npm run icons` (scripts/generate-icons.mjs):
   the repository root's logo, the bundler copy the site reaches, and the
   hatch and auth favicons. This refuses the drift either way - a change to
   the geometry that was not regenerated, or a hand edit to a generated file.
   The PNG icons are not compared: a raster differs by sharp version, and the
   script's own comment says to look at them instead. Read off disk the way
   topBarCss.test.ts reaches into @hatch/ui's own files. */
/// <reference types="node" />
import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { hatchMarkSvg } from '@hatch/ui';

const web = new URL('../../../../', import.meta.url);
const generated = {
  'hatch-logo.svg at the repository root': new URL('../../hatch-logo.svg', web),
  'the bundler copy in packages/ui/src/assets': new URL('packages/ui/src/assets/hatch-logo.svg', web),
  "the board's favicon": new URL('apps/hatch/public/favicon.svg', web),
  "the sign-in page's favicon": new URL('apps/auth/public/favicon.svg', web),
};

/** The file without its leading "generated by" comment, which is the one
    part of it the source does not state. */
const withoutComment = (svg: string) => svg.replace(/^<!--[\s\S]*?-->\s*/, '');

describe('the generated renderings of the mark', () => {
  const source = hatchMarkSvg({ fill: 'gradient' });

  it('draw the two paths in the gradient', () => {
    expect(source).toContain('<linearGradient');
    expect(source.match(/<path /g)).toHaveLength(2);
  });

  for (const [name, file] of Object.entries(generated)) {
    it(`${name} is what hatchMark.ts generates`, () => {
      const text = readFileSync(file, 'utf8');
      expect(text.startsWith('<!-- Generated by `npm run icons`')).toBe(true);
      expect(withoutComment(text)).toBe(source);
    });
  }
});
